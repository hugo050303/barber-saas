-- ---------- TABLAS ----------

create table if not exists public.configuracion (
  id              int primary key default 1,
  nombre_negocio  text default 'Mi Barbería',
  direccion       text default '',
  telefono        text default '',
  mensaje_ticket  text default '¡Gracias por su preferencia!',
  constraint configuracion_una_fila check (id = 1)
);
insert into public.configuracion (id) values (1) on conflict (id) do nothing;

create table if not exists public.barberos (
  id                   bigint generated by default as identity primary key,
  nombre               text not null,
  especialidad         text,
  porcentaje_comision  numeric default 50,
  created_at           timestamptz default now()
);

create table if not exists public.servicios (
  id            bigint generated by default as identity primary key,
  nombre        text not null,
  precio        numeric not null default 0,
  duracion_min  int default 30,
  created_at    timestamptz default now()
);

create table if not exists public.clientes (
  id          bigint generated by default as identity primary key,
  nombre      text not null,
  telefono    text,
  notas       text,
  created_at  timestamptz default now()
);

create table if not exists public.citas (
  id                bigint generated by default as identity primary key,
  cliente_nombre    text not null,
  cliente_telefono  text,
  fecha_hora        timestamptz not null,
  barbero_id        bigint references public.barberos(id) on delete set null,
  servicio_id       bigint references public.servicios(id) on delete set null,
  estado            text not null default 'pendiente',
  created_at        timestamptz default now()
);
create index if not exists citas_fecha_hora_idx on public.citas (fecha_hora);

create table if not exists public.inventario (
  id            bigint generated by default as identity primary key,
  nombre        text not null,
  precio_venta  numeric not null default 0,
  stock         int not null default 0,
  created_at    timestamptz default now()
);

create table if not exists public.ventas_productos (
  id             bigint generated by default as identity primary key,
  total          numeric not null default 0,
  detalle_items  jsonb,
  fecha          timestamptz default now()
);

create table if not exists public.gastos (
  id           bigint generated by default as identity primary key,
  descripcion  text not null,
  monto        numeric not null default 0,
  categoria    text,
  fecha        timestamptz default now()
);

create table if not exists public.cortes_caja (
  id               bigint generated by default as identity primary key,
  total_servicios  numeric default 0,
  total_ventas     numeric default 0,
  total_gastos     numeric default 0,
  dinero_en_caja   numeric default 0,
  fecha            timestamptz default now()
);

-- ---------- SEGURIDAD (Row Level Security) ----------
-- Usuarios con sesión iniciada (el dueño / staff): acceso total.
-- Visitantes anónimos (página /reservar): solo pueden ver barberos,
-- servicios y el nombre del negocio, y crear citas/clientes.

do $$
declare t text;
begin
  foreach t in array array['configuracion','barberos','servicios','clientes','citas',
                           'inventario','ventas_productos','gastos','cortes_caja']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "staff_todo" on public.%I', t);
    execute format('create policy "staff_todo" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

drop policy if exists "publico_ver_barberos" on public.barberos;
create policy "publico_ver_barberos" on public.barberos for select to anon using (true);

drop policy if exists "publico_ver_servicios" on public.servicios;
create policy "publico_ver_servicios" on public.servicios for select to anon using (true);

drop policy if exists "publico_ver_config" on public.configuracion;
create policy "publico_ver_config" on public.configuracion for select to anon using (true);

drop policy if exists "publico_crear_cita" on public.citas;
create policy "publico_crear_cita" on public.citas for insert to anon
  with check (estado = 'pendiente');

drop policy if exists "publico_crear_cliente" on public.clientes;
create policy "publico_crear_cliente" on public.clientes for insert to anon with check (true);
