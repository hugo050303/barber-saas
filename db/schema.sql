-- ---------------------------------------------------------------------
-- Configuración del negocio (una sola fila con id = 1)
-- Usado en: Configuracion.jsx, Sidebar.jsx, Venta.jsx (ticket)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS configuracion (
  id              integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  nombre_negocio  text NOT NULL DEFAULT 'Mi Barbería',
  direccion       text,
  telefono        text,
  mensaje_ticket  text DEFAULT '¡Gracias por su visita!',
  created_at      timestamptz NOT NULL DEFAULT now()
);

INSERT INTO configuracion (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- ---------------------------------------------------------------------
-- Barberos (equipo)
-- Usado en: Equipo.jsx, Nomina.jsx, Agenda.jsx, ModalCita.jsx, ReservaPublica.jsx
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS barberos (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre               text NOT NULL,
  especialidad         text,
  porcentaje_comision  numeric(5,2) NOT NULL DEFAULT 50
                       CHECK (porcentaje_comision BETWEEN 0 AND 100),
  created_at           timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Servicios (corte, barba, etc.)
-- Usado en: Servicios.jsx, Agenda.jsx, ModalCita.jsx, ReservaPublica.jsx
-- Nota: Agenda.jsx lee "duracion" y Servicios.jsx escribe "duracion_min";
-- "duracion" es una columna calculada para que ambos funcionen.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS servicios (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        text NOT NULL,
  precio        numeric(10,2) NOT NULL DEFAULT 0 CHECK (precio >= 0),
  duracion_min  integer NOT NULL DEFAULT 30 CHECK (duracion_min > 0),
  duracion      integer GENERATED ALWAYS AS (duracion_min) STORED,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Clientes (directorio)
-- Usado en: Clientes.jsx, ModalCita.jsx, ReservaPublica.jsx
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clientes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      text NOT NULL,
  telefono    text,
  notas       text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS clientes_nombre_idx   ON clientes (nombre);
CREATE INDEX IF NOT EXISTS clientes_telefono_idx ON clientes (telefono);

-- ---------------------------------------------------------------------
-- Citas (agenda)
-- Usado en: Agenda.jsx, ModalCita.jsx, ModalDetalles.jsx, ReservaPublica.jsx,
--           CorteCaja.jsx, Nomina.jsx, Clientes.jsx, Dashboard.jsx
-- Estados usados en la app: pendiente, confirmada, finalizada, cancelada
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS citas (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_nombre    text NOT NULL,
  cliente_telefono  text,
  fecha_hora        timestamptz NOT NULL,
  barbero_id        bigint REFERENCES barberos (id) ON DELETE SET NULL,
  servicio_id       bigint REFERENCES servicios (id) ON DELETE SET NULL,
  estado            text NOT NULL DEFAULT 'pendiente'
                    CHECK (estado IN ('pendiente', 'confirmada', 'finalizada', 'cancelada')),
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS citas_fecha_hora_idx ON citas (fecha_hora);
CREATE INDEX IF NOT EXISTS citas_estado_idx     ON citas (estado);
CREATE INDEX IF NOT EXISTS citas_barbero_idx    ON citas (barbero_id);

-- ---------------------------------------------------------------------
-- Inventario (productos a la venta)
-- Usado en: Inventario.jsx, Venta.jsx
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS inventario (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        text NOT NULL,
  precio_venta  numeric(10,2) NOT NULL DEFAULT 0 CHECK (precio_venta >= 0),
  stock         integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Ventas de productos (punto de venta)
-- Usado en: Venta.jsx, CorteCaja.jsx, Dashboard.jsx
-- detalle_items guarda el carrito completo como JSON.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ventas_productos (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  total          numeric(10,2) NOT NULL DEFAULT 0,
  detalle_items  jsonb NOT NULL DEFAULT '[]'::jsonb,
  fecha          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ventas_productos_fecha_idx ON ventas_productos (fecha);

-- ---------------------------------------------------------------------
-- Gastos
-- Usado en: Gastos.jsx, CorteCaja.jsx, Dashboard.jsx
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gastos (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion  text NOT NULL,
  monto        numeric(10,2) NOT NULL DEFAULT 0 CHECK (monto >= 0),
  categoria    text,
  fecha        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gastos_fecha_idx ON gastos (fecha);

-- ---------------------------------------------------------------------
-- Cortes de caja (cierres del día)
-- Usado en: CorteCaja.jsx
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cortes_caja (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  total_servicios  numeric(10,2) NOT NULL DEFAULT 0,
  total_ventas     numeric(10,2) NOT NULL DEFAULT 0,
  total_gastos     numeric(10,2) NOT NULL DEFAULT 0,
  dinero_en_caja   numeric(10,2) NOT NULL DEFAULT 0,
  fecha            timestamptz NOT NULL DEFAULT now()
);
